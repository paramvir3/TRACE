"""Generate docs/electrostatics_api.md from trace_electrostatics' public API.

Every name in ``trace_electrostatics.__all__``, grouped by the module that
defines it, with its signature and the first paragraph of its docstring.  The
page is generated, never edited by hand; ``tests/electrostatics/
test_api_reference.py`` fails when it is out of date.

Usage: python tools/gen_electrostatics_api.py [--check]
"""
from __future__ import annotations

import inspect
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "electrostatics_api.md"

#: Constants have no docstring of their own (``getdoc`` would describe ``float``).
CONSTANTS = {
    "ENERGY_UNIT": "Unit of every energy in the package.",
    "LENGTH_UNIT": "Unit of every length in the package.",
    "CHARGE_UNIT": "Unit of every charge in the package.",
    "K_E": "Coulomb constant e^2 / (4 pi eps_0) in eV*A/e^2.",
    "METAL_BOND_HARDNESS": "Hardness of the zero-hardness star and circuit bonds of metals (SPEC 20), eV/e^2.",
}

MODULE_TITLES = {
    "trace_electrostatics.constants": "Units and constants",
    "trace_electrostatics.config": "Configuration",
    "trace_electrostatics.heads": "Equivariant heads",
    "trace_electrostatics.energy": "Energy, state and the model hook",
    "trace_electrostatics.solver": "Solve results and parameters",
    "trace_electrostatics.implicit": "Converged solve (errors)",
    "trace_electrostatics.observables": "Observables (response properties)",
    "trace_electrostatics.dispersion": "Dispersion",
    "trace_electrostatics.kernels": "Kernels and the hardness floor",
    "trace_electrostatics.open_operator": "Matrix-free operators",
    "trace_electrostatics.charge_states": "Diabatic charge states (SPEC 21)",
    "trace_electrostatics.transfer_coupling": "Through-bond coupling (SPEC 22)",
    "trace_electrostatics.metals": "Metals and electrodes (SPEC 20)",
}


def _first_paragraph(obj) -> str:
    doc = inspect.getdoc(obj) or ""
    return " ".join(doc.split("\n\n")[0].split())


def _annotation(annotation) -> str:
    """An annotation as plain text, identically on every Python version.

    ``str(inspect.signature(...))`` is not: 3.12 prints a NamedTuple field as
    ``ForwardRef('Tensor')`` where 3.8 prints ``'Tensor'``.
    """
    import typing

    if isinstance(annotation, typing.ForwardRef):
        annotation = annotation.__forward_arg__
    if isinstance(annotation, str):
        text = annotation
        while len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
            text = text[1:-1]
        return text
    return getattr(annotation, "__name__", repr(annotation))


def _signature(name, obj) -> str:
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return name
    parts, keyword_marker = [], False
    for parameter in sig.parameters.values():
        if parameter.kind is parameter.KEYWORD_ONLY and not keyword_marker:
            parts.append("*")
            keyword_marker = True
        text = parameter.name
        if parameter.kind is parameter.VAR_POSITIONAL:
            text, keyword_marker = "*" + text, True
        elif parameter.kind is parameter.VAR_KEYWORD:
            text = "**" + text
        if parameter.annotation is not parameter.empty:
            text += ": " + _annotation(parameter.annotation)
        if parameter.default is not parameter.empty:
            text += " = " + repr(parameter.default)
        parts.append(text)
    result = f"{name}({', '.join(parts)})"
    if sig.return_annotation is not sig.empty:
        result += " -> " + _annotation(sig.return_annotation)
    return result


def render() -> str:
    import torch

    torch.set_default_dtype(torch.float64)
    sys.path.insert(0, str(ROOT))
    import trace_electrostatics as package

    groups: dict = {}
    for name in package.__all__:
        obj = getattr(package, name)
        if name in CONSTANTS:
            module = "trace_electrostatics.constants" if name != "METAL_BOND_HARDNESS" \
                else "trace_electrostatics.metals"
        else:
            module = getattr(obj, "__module__", "trace_electrostatics")
        groups.setdefault(module, []).append((name, obj))

    lines = [
        "# `trace_electrostatics` API reference",
        "",
        "Generated by `tools/gen_electrostatics_api.py` from the package itself; do not edit.",
        "Every public name (`trace_electrostatics.__all__`), its signature and the first",
        "paragraph of its docstring. The user guide is [electrostatics.md](electrostatics.md);",
        "the physics contract is `trace_electrostatics/SPEC.md`.",
        "",
    ]
    order = list(MODULE_TITLES) + sorted(set(groups) - set(MODULE_TITLES))
    for module in order:
        if module not in groups:
            continue
        lines += [f"## {MODULE_TITLES.get(module, module)}", "", f"`{module}`", ""]
        for name, obj in groups[module]:
            if name in CONSTANTS:
                lines += [f"### `{name}`", "", f"`{name} = {obj!r}` -- {CONSTANTS[name]}", ""]
                continue
            kind = "class" if inspect.isclass(obj) else "function"
            lines += [f"### `{name}` ({kind})", "", "```python", _signature(name, obj), "```", ""]
            summary = _first_paragraph(obj)
            if summary:
                lines += [summary, ""]
    return "\n".join(lines).rstrip() + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print("docs/electrostatics_api.md is out of date: run python tools/gen_electrostatics_api.py")
            sys.exit(1)
        print("up to date")
        return
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
